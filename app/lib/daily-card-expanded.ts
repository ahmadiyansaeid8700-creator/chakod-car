export const DAILY_CARD_TEXT_VARIANTS = QUOTE_GROUPS.reduce(
  (total, group) => total + group.leads.length * group.tailOpeners.length * group.tails.length,
  0,
);

function hashString(value: string) {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function mix(seed: number, salt: number) {
  let value = (seed ^ Math.imul(salt, 0x9e3779b1)) >>> 0;
  value ^= value >>> 16;
  value = Math.imul(value, 0x85ebca6b) >>> 0;
  value ^= value >>> 13;
  value = Math.imul(value, 0xc2b2ae35) >>> 0;
  return (value ^ (value >>> 16)) >>> 0;
}

export function buildDailyCard(userKey: string, date = new Date()): DailyCardRecipe {
  const dateKey = getDailyCardDateKey(date);
  const seed = hashString(`${userKey.trim() || "chakod"}|${dateKey}|expanded-v1`);
  const group = QUOTE_GROUPS[mix(seed, 1) % QUOTE_GROUPS.length];
  const lead = group.leads[mix(seed, 2) % group.leads.length];
  const tailOpener = group.tailOpeners[mix(seed, 3) % group.tailOpeners.length];
  const tail = group.tails[mix(seed, 4) % group.tails.length];
  const style = DAILY_CARD_STYLES[mix(seed, 5) % DAILY_CARD_STYLES.length];

  return {
    quote: `${lead}؛ ${tailOpener}${tail}.`,
    style,
    motif: (mix(seed, 6) % 4) as 0 | 1 | 2 | 3,
    glowX: 18 + (mix(seed, 7) % 65),
    glowY: 10 + (mix(seed, 8) % 72),
    rotation: ((mix(seed, 9) % 81) - 40) / 10,
  };
}
