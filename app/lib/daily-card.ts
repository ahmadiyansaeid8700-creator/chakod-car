function hashString(value: string) {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function mix(seed: number, salt: number) {
  let value = (seed ^ Math.imul(salt, 0x9e3779b1)) >>> 0;
  value ^= value >>> 16;
  value = Math.imul(value, 0x85ebca6b) >>> 0;
  value ^= value >>> 13;
  value = Math.imul(value, 0xc2b2ae35) >>> 0;
  return (value ^ (value >>> 16)) >>> 0;
}

export function getDailyCardDateKey(date = new Date()) {
  try {
    return new Intl.DateTimeFormat("en-CA", {
      timeZone: "Asia/Tehran",
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
    }).format(date);
  } catch {
    return date.toISOString().slice(0, 10);
  }
}

export function formatPersianCardDate(date = new Date()) {
  try {
    return {
      weekday: new Intl.DateTimeFormat("fa-IR-u-ca-persian", {
        timeZone: "Asia/Tehran",
        weekday: "long",
      }).format(date),
      date: new Intl.DateTimeFormat("fa-IR-u-ca-persian", {
        timeZone: "Asia/Tehran",
        day: "numeric",
        month: "long",
        year: "numeric",
      }).format(date),
    };
  } catch {
    return { weekday: "امروز", date: "" };
  }
}

export function buildDailyCard(userKey: string, date = new Date()): DailyCardRecipe {
  const dateKey = getDailyCardDateKey(date);
  const seed = hashString(`${userKey.trim() || "chakod"}|${dateKey}`);
  const group = QUOTE_GROUPS[mix(seed, 1) % QUOTE_GROUPS.length];
  const lead = group.leads[mix(seed, 2) % group.leads.length];
  const tail = group.tails[mix(seed, 3) % group.tails.length];
  const style = DAILY_CARD_STYLES[mix(seed, 4) % DAILY_CARD_STYLES.length];

  return {
    quote: `${lead}؛ ${tail}.`,
    style,
    motif: (mix(seed, 5) % 4) as 0 | 1 | 2 | 3,
    glowX: 18 + (mix(seed, 6) % 65),
    glowY: 10 + (mix(seed, 7) % 72),
    rotation: ((mix(seed, 8) % 81) - 40) / 10,
  };
}

export function getIdentityInitials(name: string) {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return "چ";
  if (parts.length === 1) return parts[0].slice(0, 2);
  return `${parts[0].slice(0, 1)}${parts[parts.length - 1].slice(0, 1)}`;
}
